-- 觸發器【add_feature_to_company_module】: 新增 FEATURES 後, 自動加到公司 ID = 1 的對應模組
CREATE OR REPLACE FUNCTION add_feature_to_company_module()
RETURNS TRIGGER AS $$
DECLARE
    company_module_id INT;
BEGIN
    SELECT ID INTO company_module_id
    FROM COMPANIES_MODULES
    WHERE COMPANY_ID = 1 AND MODULE_ID = NEW.MODULE_ID;

    INSERT INTO COMPANIES_MODULES_FEATURES (COMPANY_MODULE_ID, FEATURE_ID, IS_ACTIVE)
    VALUES (company_module_id, NEW.ID, TRUE);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_add_feature_to_company_module
AFTER INSERT ON FEATURES
FOR EACH ROW
EXECUTE FUNCTION add_feature_to_company_module();

