            CASE_PATROL_ID, CASE_NUM, DT_RECORD, CAR, PRJ_ID, IMG, IMG_DETECT, CRACKTYPE, DEGREE,
            CRACK_ID, LENGTH, WIDTH, AREA, IMG_MAP_AREA, LONGITUDE, LATITUDE)
