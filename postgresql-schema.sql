-- 觸發器【add_module_to_company】: 新增/更新 MODULES 後, 自動把該模組加給公司 ID = 1
CREATE OR REPLACE FUNCTION add_module_to_company()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO COMPANIES_MODULES (COMPANY_ID, MODULE_ID, IS_ACTIVE)
    VALUES (1, NEW.ID, TRUE);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_add_module_to_company
AFTER INSERT OR UPDATE ON MODULES
FOR EACH ROW
EXECUTE FUNCTION add_module_to_company();

