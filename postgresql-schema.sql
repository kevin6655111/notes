CREATE OR REPLACE FUNCTION check_case_num_unique_case_survey()
RETURNS TRIGGER AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM CASE_SURVEY WHERE CASE_NUM = NEW.CASE_NUM AND ID <> NEW.ID) THEN
        RAISE EXCEPTION 'DUPLICATE CASE_NUM: %', NEW.CASE_NUM;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_before_check_case_num_unique_case_survey
BEFORE INSERT OR UPDATE ON CASE_SURVEY
FOR EACH ROW EXECUTE FUNCTION check_case_num_unique_case_survey();

--【CASE_SURVEY_REF】: 對【CASE_SURVEY】綁外鍵的中間表
CREATE TABLE IF NOT EXISTS CASE_SURVEY_REF (
    ID INT PRIMARY KEY,
    DT_RECORD TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE OR REPLACE FUNCTION insert_case_survey_ref()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO CASE_SURVEY_REF (ID, DT_RECORD) VALUES (NEW.ID, NEW.DT_RECORD)
    ON CONFLICT (ID) DO UPDATE SET DT_RECORD = EXCLUDED.DT_RECORD;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_after_insert_case_survey_ref
AFTER INSERT OR UPDATE ON CASE_SURVEY
FOR EACH ROW
EXECUTE FUNCTION insert_case_survey_ref();

CREATE OR REPLACE FUNCTION delete_case_survey_ref()
RETURNS TRIGGER AS $$
BEGIN
    DELETE FROM CASE_SURVEY_REF WHERE ID = OLD.ID;
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_before_delete_case_survey_ref
BEFORE DELETE ON CASE_SURVEY
FOR EACH ROW
EXECUTE FUNCTION delete_case_survey_ref();

