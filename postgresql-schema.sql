            OLD.CRACK_ID, OLD.LENGTH, OLD.WIDTH, OLD.AREA, OLD.IMG_MAP_AREA, OLD.LONGITUDE, OLD.LATITUDE
        );
    END IF;
    RETURN NEW;
END;
